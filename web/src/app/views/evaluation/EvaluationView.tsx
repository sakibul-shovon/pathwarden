import { useCallback, useEffect, useState, type ReactNode } from "react";
import { api } from "../../../api/client";
import type { EvalSummary } from "../../../api/types";
import { EmptyState } from "../../../shared/components/EmptyState";
import { ErrorPanel } from "../../../shared/components/ErrorPanel";
import { IdChip } from "../../../shared/components/IdChip";
import { Skeleton } from "../../../shared/components/Skeleton";
import { describeError } from "../../errorCatalogue";
import { CriteriaList, DefenseTable, FamilyTable, JudgeMeta, Limitations, RemediationTable, WitnessAccuracy } from "./Report";
import { IntervalChart } from "./IntervalChart";
import { defenseRows } from "./evalLogic";
import "./evaluation.css";

const FILES = ["eval/results/summary.md", "eval/results/summary.json", "eval/results/results.csv"];

const Section = ({ id, title, children }: { id: string; title: string; children: ReactNode }) => (
  <section aria-labelledby={id} className="pw-report__section">
    <h3 id={id} className="pw-report__h">
      {title}
    </h3>
    {children}
  </section>
);

/** The generated evaluation, presented honestly, including where Pathwarden is not better (ui-redesign.md §13.9). Every number and
 *  sentence is read from `GET /api/eval/summary`, i.e. from the file `make eval` wrote: none is typed here and none is recomputed. */
export function EvaluationView() {
  const [summary, setSummary] = useState<EvalSummary | null>(null);
  const [error, setError] = useState<unknown>(null);
  const [loading, setLoading] = useState(true);

  const load = useCallback(() => {
    api
      .evalSummary()
      .then((s) => {
        setSummary(s);
        setError(null);
      })
      .catch((err: unknown) => setError(err))
      .finally(() => setLoading(false));
  }, []);

  // the report changes only when `make eval` is run, so it is read on arrival and again whenever the window regains focus
  useEffect(() => {
    load();
    window.addEventListener("focus", load);
    return () => window.removeEventListener("focus", load);
  }, [load]);

  const failure = error ? describeError(error) : null;

  if (loading && !summary) return <Skeleton lines={6} height={24} />;
  if (!summary) {
    if (failure?.code === "eval_not_run") {
      return (
        <EmptyState>
          No evaluation results yet. Run <code>make eval</code>, then come back: the report is generated from its output.
        </EmptyState>
      );
    }
    return (
      <ErrorPanel title={failure?.title ?? "Could not load the evaluation"} code={failure?.code ?? "load_error"}>
        {failure?.hint && <p>{failure.hint}</p>}
        {failure?.detail && <p className="pw-muted">{failure.detail}</p>}
      </ErrorPanel>
    );
  }

  const rows = defenseRows(summary);
  return (
    <article className="pw-report">
      <header className="pw-report__head">
        <h2 className="pw-report__title">Evaluation report</h2>
        <p>
          {summary.dataset.scenarios} scenarios ({summary.dataset.attacks} attacks, {summary.dataset.benign} benign), seed {summary.dataset.seed}.
        </p>
        <p className="pw-muted">
          <strong>ASR</strong> is attacks released over attacks; <strong>FHR</strong> is benign actions held or blocked over benign actions. The interval is the
          Wilson 95% interval.
        </p>
      </header>
      {failure && (
        <ErrorPanel title={failure.title} code={failure.code}>
          <p className="pw-muted">The report below was loaded earlier and may be out of date.</p>
        </ErrorPanel>
      )}

      <Section id="pw-eval-chart" title="Attack success and false holds">
        <IntervalChart rows={rows} />
      </Section>
      <Section id="pw-eval-defenses" title="Defenses">
        <DefenseTable s={summary} />
        <WitnessAccuracy s={summary} />
      </Section>
      <Section id="pw-eval-criteria" title="Falsification criteria">
        <CriteriaList s={summary} />
      </Section>
      <Section id="pw-eval-family" title="Per family">
        <FamilyTable s={summary} />
      </Section>
      {summary.remediation && (
        <Section id="pw-eval-remediation" title="Remediation: candidates against the brute-force optimum">
          <RemediationTable s={summary} />
        </Section>
      )}
      {summary.llm_judges && (
        <Section id="pw-eval-judges" title="LLM judges (B1 and B3)">
          <JudgeMeta s={summary} />
        </Section>
      )}
      <Section id="pw-eval-limits" title="How to read this">
        <Limitations s={summary} />
      </Section>
      <Section id="pw-eval-provenance" title="Where this comes from">
        <p className="pw-muted">
          Generated by <code>make eval</code> and never edited by hand. Files:
        </p>
        <p className="pw-report__files">
          {FILES.map((f) => (
            <IdChip key={f} id={f} copyable />
          ))}
        </p>
      </Section>
    </article>
  );
}
