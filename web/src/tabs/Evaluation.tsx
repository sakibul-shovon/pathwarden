import { useState } from "react";
import { api } from "../api/client";
import type { DefenseSummary, EvalSummary, Proportion } from "../api/types";
import { usePoll } from "../hooks";
import { ViewHeader } from "../shell/AppShell";
import { Icon } from "../ui/Icon";
import { IntervalPlot, pct } from "../ui/IntervalPlot";

function Rate({ p }: { p: Proportion }) {
  return (
    <>
      <strong>{pct(p.rate)}</strong>{" "}
      <span className="muted">[{pct(p.lo)}, {pct(p.hi)}] ({p.k}/{p.n})</span>
    </>
  );
}

function DefenseRow({ name, d }: { name: string; d: DefenseSummary }) {
  if (d.status !== "run") {
    return (
      <tr>
        <td>{name}</td>
        <td colSpan={2} className="notrun">not_run (needs the live LLM mode, phase P8)</td>
      </tr>
    );
  }
  return (
    <tr>
      <td>{name}</td>
      <td><Rate p={d.asr} /></td>
      <td><Rate p={d.fhr} /></td>
    </tr>
  );
}

function FamilyCell({ cell }: { cell: EvalSummary["per_family"][string][string] | undefined }) {
  if (!cell || cell.status === "not_run") return <td className="notrun">not_run</td>;
  if (cell.attacks !== undefined) return <td className="num">{cell.released}/{cell.attacks} released</td>;
  return <td className="num">{cell.held}/{cell.benign} held</td>;
}

/** Everything here is rendered from `GET /api/eval/summary`, i.e. from the file `make eval` wrote.
 *  No number, interval or criterion is typed in this component. */
export function EvaluationTab() {
  const summary = usePoll(api.evalSummary, 10000);
  const [asTable, setAsTable] = useState(false);
  const s = summary.data;

  if (summary.error && !s) {
    return (
      <section aria-label="Evaluation">
        <ViewHeader id="evaluation" />
        <div className="notice notice-hold" role="alert">
          <Icon name="alert" /> <span>{summary.error} Generate the results with <code>make eval</code>.</span>
        </div>
      </section>
    );
  }
  if (!s) {
    return (
      <section aria-label="Evaluation">
        <ViewHeader id="evaluation" />
        <div className="panel skeleton-panel" aria-busy="true"><span className="skeleton sk-title" /><span className="skeleton sk-graph" /><span className="sr-only">Loading…</span></div>
      </section>
    );
  }

  const defenses = Object.keys(s.defenses);
  return (
    <section aria-label="Evaluation">
      <ViewHeader id="evaluation" />

      <div className="panel">
        <div className="panel-head">
          <h2>Defenses compared</h2>
          <button type="button" className="btn btn-quiet" onClick={() => setAsTable(!asTable)} aria-pressed={asTable}>
            <Icon name="route" /> {asTable ? "View as plots" : "View as table"}
          </button>
        </div>
        <p>
          {s.dataset.scenarios} scenarios ({s.dataset.attacks} attacks, {s.dataset.benign} benign), seed {s.dataset.seed}.{" "}
          <strong>ASR</strong> = attacks released / attacks; <strong>FHR</strong> = benign held or blocked / benign;
          Wilson 95% interval in brackets. Files: <code>eval/results/summary.md</code>, <code>summary.json</code>,{" "}
          <code>results.csv</code> (generated by <code>make eval</code>, never edited by hand).
        </p>
        {asTable ? (
          <div className="scroll">
            <table>
              <thead><tr><th>Defense</th><th>ASR (lower is better)</th><th>FHR (lower is better)</th></tr></thead>
              <tbody>{defenses.map((name) => <DefenseRow key={name} name={name} d={s.defenses[name] as DefenseSummary} />)}</tbody>
            </table>
          </div>
        ) : (
          <div className="plots">
            <IntervalPlot title="Attacks released (ASR, lower is better)" pick={(d) => d.asr} defenses={s.defenses} />
            <IntervalPlot title="Benign actions held (FHR, lower is better)" pick={(d) => d.fhr} defenses={s.defenses} />
          </div>
        )}
        <p className="stat-line">
          Witness accuracy (PW): <strong className="mono">{s.witness_accuracy.correct}/{s.witness_accuracy.n}</strong> ({pct(s.witness_accuracy.rate)}).
        </p>
      </div>

      <div className="panel">
        <h2>Falsification criteria</h2>
        <ul className="criteria">
          {s.falsification_criteria.map((c) => (
            <li key={c.text}>
              <span>{c.text}</span> <strong className="criteria-status">Status: {c.status}</strong>
            </li>
          ))}
        </ul>
      </div>

      <div className="panel scroll">
        <h2>Per family</h2>
        <table>
          <thead>
            <tr><th>Family</th>{defenses.map((d) => <th key={d}>{d}</th>)}</tr>
          </thead>
          <tbody>
            {Object.keys(s.per_family).map((family) => (
              <tr key={family}>
                <td>{family}</td>
                {defenses.map((d) => <FamilyCell key={d} cell={s.per_family[family]?.[d]} />)}
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {s.remediation && (
        <div className="panel scroll">
          <h2>Remediation: candidates vs brute-force optimum</h2>
          <table>
            <thead><tr><th>Topology</th><th>Candidates (cost)</th><th className="num">Best</th><th className="num">Optimum</th><th className="num">Gap</th></tr></thead>
            <tbody>
              {Object.entries(s.remediation).map(([name, r]) => (
                <tr key={name}>
                  <td>{name}</td>
                  <td>{r.candidates.map((c) => `${c.id}=${c.total_cost}`).join(", ")}</td>
                  <td className="num">{r.best_candidate_cost}</td>
                  <td className="num">{r.optimum_cost ?? "none ≤ 6 edges"}</td>
                  <td className="num">{r.gap ?? "—"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      <div className="panel limits-panel">
        <h2>How to read this</h2>
        <ul className="limits">{s.limitations.map((text) => <li key={text}>{text}</li>)}</ul>
      </div>
    </section>
  );
}
